def split_front_matter(text: str) -> tuple[dict[str, Any], str]:
    """Parse a page's ``---`` YAML front matter. Returns ``({}, text)`` when absent.

    Deliberately a tiny hand-rolled parser rather than a PyYAML dependency: the schema is
    fixed and shallow (scalars plus one-level lists), and the documentation tooling should
    not add a runtime dependency to the package's dev environment for five keys.
    """
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return {}, text
    block, body = text[4:end], text[end + 5 :]

    data: dict[str, Any] = {}
    key: str | None = None
    for raw in block.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith("  - ") or raw.startswith("- "):
            if key is None:
                continue
            data.setdefault(key, [])
            if not isinstance(data[key], list):
                data[key] = []
            data[key].append(raw.split("- ", 1)[1].strip().strip("\"'"))
            continue
        if ":" not in raw:
            continue
        key, _, value = raw.partition(":")
        key = key.strip()
        value = value.strip().strip("\"'")
        data[key] = value if value else []
    return data, body


def _yaml_scalar(value: Any) -> str:
    """Render a scalar so the front matter stays valid YAML.

    gelpy's own parser partitions on the first colon and would not care, but the front matter
    is a YAML block and readers (editors, linters, a future mkdocs plugin) parse it as one. An
    unquoted value containing ": " makes the document invalid, which a page title easily does
    -- "Concepts: the run folder" was exactly that.
    """
    text = str(value)
    needs_quotes = (
        ": " in text
        or text.endswith(":")
        or text.startswith(("&", "*", "!", "%", "@", "`", "[", "{", ">", "|", "'", '"', "#"))
        or text.strip() != text
    )
    if not needs_quotes:
        return text
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_front_matter(data: dict[str, Any]) -> str:
    """Serialize front matter in a fixed key order, so a re-stamp is a one-line diff."""
    order = ["title", "audience", "summary", "subject", "subject_digest"]
    lines = ["---"]
    for key in order + [k for k in data if k not in order]:
        if key not in data:
            continue
        value = data[key]
        if isinstance(value, list):
            lines.append(f"{key}:")
            lines.extend(f"  - {_yaml_scalar(item)}" for item in value)
        else:
            lines.append(f"{key}: {_yaml_scalar(value)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def page_subjects(front: dict[str, Any]) -> list[Path]:
    subjects = front.get("subject") or []
    if isinstance(subjects, str):
        subjects = [subjects]
    return [REPO / s for s in subjects]


def guide_pages() -> list[Path]:
    return sorted(GUIDE.glob("*.md")) if GUIDE.exists() else []


