#!/usr/bin/env python3
"""Build and verify gelpy's documentation.

The governing rule: **if the runtime can print it, documentation must not copy it.**
``gelpy --help``, ``gelpy schema <Model>`` and ``gelpy models list`` are already complete,
machine-readable and definitionally current, so a hand-written copy of any of them can only
decay. Everything in ``docs/reference/`` is therefore generated from the code here, and
``tests/docs/test_reference_is_current.py`` regenerates and diffs it, which makes drift a
test failure rather than a discovery.

Hand-written narrative under ``docs/guide/`` cannot be generated -- it explains *why* -- so
each page instead declares the source files it describes plus a digest of their public
surface (see ``tools/_api_digest.py``). When those signatures, defaults or Field descriptions
move, a test names the page for review.

Commands
--------
    python tools/docs.py build            # regenerate docs/reference/ + docs/docs-index.json
    python tools/docs.py check            # report drift, write nothing, exit 1 if any
    python tools/docs.py accept [PAGE]    # re-stamp a page after re-reading it
    python tools/docs.py digest PATH...   # print the digest of some files (debugging)
    python tools/docs.py surface PATH...  # print the digest's input text (debugging)
"""

from __future__ import annotations

import argparse
import json
