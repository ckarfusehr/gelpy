def build_index() -> dict[str, Any]:
    """A machine-readable map of the documentation set.

    An agent reads this one small file to decide which page is worth opening, instead of
    grepping every document. Generated from front matter, so it cannot describe a page that
    does not exist.
    """
    pages = []
    for path in guide_pages() + sorted(WALKTHROUGH.glob("*.md")):
        front, body = split_front_matter(path.read_text())
        if not front:
            # No front matter means this is not a documentation page -- e.g. report.md, a
            # generated artifact of the example run that lives alongside the walkthrough.
            continue
        pages.append(
            {
                "path": str(path.relative_to(REPO)),
                "title": front.get("title", path.stem),
                "audience": front.get("audience", "both"),
                "summary": front.get("summary", ""),
                "subject": front.get("subject", []),
                "claims": sorted(_claim_ids(body)),
                "lines": len(body.splitlines()),
            }
        )
    return {
        "_comment": (
            "Generated by tools/docs.py -- a routing table for this documentation set. "
            "'audience' is a hint, not a restriction; 'subject' lists the source files a page "
            "describes; 'claims' are facts asserted by tests/docs/test_claims.py."
        ),
        "generated_reference": sorted(GENERATORS),
        "pages": pages,
    }


def _claim_ids(text: str) -> set[str]:
    """Claim ids cited inline as ``<!-- claim: <id> -->``.

    Fenced blocks and inline code spans are stripped first: a citation shown as code is an
    illustration of the syntax, not a citation of a fact.
    """
    import re

    body = re.sub(r"^```.*?^```", "", text, flags=re.S | re.M)
    body = re.sub(r"`[^`\n]*`", "", body)
    return set(re.findall(r"<!--\s*claim:\s*([a-z0-9-]+)\s*-->", body))


