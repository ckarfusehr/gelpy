def _md_table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_none_\n"
        # (kept explicit: an empty registry should read as empty, not as a broken table)
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for row in rows:
        out.append("| " + " | ".join(cell.replace("|", "\\|") for cell in row) + " |")
    return "\n".join(out) + "\n"


def _clean(text: str | None) -> str:
    return " ".join((text or "").split())


def generate_cli() -> str:
    """The full command tree, from the typer app itself."""
    import typer.main

    from gelpy.cli.app import app

    command = typer.main.get_command(app)

    def _is_argument(param: Any) -> bool:
        """Positional argument vs option.

        Deliberately not ``isinstance(param, click.Argument)``: typer vendors its own click
        (``typer._click.core``), so the top-level ``click.Argument`` is not in the MRO and the
        isinstance check silently returns False for every parameter -- which put every
        positional argument in the options table. ``param_type_name`` is click's own
        discriminator and is set on both classes in either copy.
        """
        kind = getattr(param, "param_type_name", None)
        if kind is not None:
            return kind == "argument"
        return not any(opt.startswith("-") for opt in getattr(param, "opts", []))

    def _type_name(param: Any) -> str:
        name = getattr(param.type, "name", str(param.type))
        if getattr(param, "multiple", False):
            name += " (repeatable)"
        return f"`{name}`"

    def render_params(cmd: Any) -> str:
        args_rows, opt_rows = [], []
        for param in cmd.params:
            if param.name == "help":
                continue
            if _is_argument(param):
                required = "**required**" if param.required else "optional"
                args_rows.append(
                    [
                        f"`{param.name.upper()}`",
                        _type_name(param),
                        required,
                        _clean(getattr(param, "help", "")),
                    ]
                )
            else:
                flags = ", ".join(f"`{o}`" for o in param.opts + param.secondary_opts)
                default = "" if param.default in (None, False) else f"`{param.default}`"
                opt_rows.append([flags, _type_name(param), default, _clean(param.help)])
        out = ""
        if args_rows:
            out += "\n" + _md_table(["argument", "type", "required", "description"], args_rows)
        if opt_rows:
            out += "\n" + _md_table(["option", "type", "default", "description"], opt_rows)
        return out

    lines = [
        GENERATED_MARKER,
        "",
        "# CLI reference",
        "",
        "Every command that touches a run folder takes the run directory as an explicit",
        "positional argument, so there is no ambient 'current run' state and a shell history is",
        "self-contained and replayable. `--format json` (the default on most commands) makes every",
        "command's output machine-readable.",
        "",
        "This page is generated from the typer application, so it cannot describe a flag that does",
        "not exist. `gelpy <command> --help` prints the same information at the terminal.",
        "",
    ]

    groups = getattr(command, "commands", {})
    for name in sorted(groups):
        sub = groups[name]
        lines.append(f"## `gelpy {name}`")
        lines.append("")
        lines.append(_clean(sub.help) or "_no description_")
        lines.append("")
        nested = getattr(sub, "commands", None)
        if nested:
            for sub_name in sorted(nested):
                leaf = nested[sub_name]
                lines.append(f"### `gelpy {name} {sub_name}`")
                lines.append("")
                lines.append(_clean(leaf.help) or "_no description_")
                lines.append(render_params(leaf))
        else:
            lines.append(render_params(sub))
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_contracts() -> str:
    """Every pydantic contract that `gelpy schema <Name>` can print."""
    import gelpy.schemas as schemas
    from gelpy.schemas.common import CanonicalModel

    lines = [
        GENERATED_MARKER,
        "",
        "# Data contracts",
        "",
        "Every request, result and configuration object gelpy exchanges. All of them subclass",
        "`CanonicalModel` (`extra=\"forbid\"`), so an unrecognised field is a hard validation error",
        "rather than a silently ignored typo.",
        "",
        "`gelpy schema <Name>` prints any of these as JSON Schema at the terminal -- prefer that",
        "over reading this page when you need the machine-readable form.",
        "",
    ]
    for name in sorted(schemas.__all__):
        obj = getattr(schemas, name)
        if not (isinstance(obj, type) and issubclass(obj, CanonicalModel)):
            continue  # type aliases (LaneSelector, NormalizationType) have no fields
        lines.append(f"## `{name}`")
        lines.append("")
        lines.append(_clean(obj.__doc__) or "_no description_")
        lines.append("")
        rows = []
        for field_name, field in obj.model_fields.items():
            annotation = getattr(field.annotation, "__name__", str(field.annotation))
            annotation = annotation.replace("typing.", "").replace("gelpy.schemas.", "")
            if field.is_required():
                default = "**required**"
            elif field.default_factory is not None:
                default = "_factory_"
            else:
                default = f"`{field.default!r}`"
            rows.append([f"`{field_name}`", f"`{annotation}`", default, _clean(field.description)])
        lines.append(_md_table(["field", "type", "default", "description"], rows))
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_registries() -> str:
    """The four extension registries, their entries and their parameter schemas."""
    from gelpy.core.background import background_registry
    from gelpy.core.lanes import projection_strategies
    from gelpy.core.peaks import peak_registry
    from gelpy.core.peaks.strategies import fit_strategy_registry

    registries = [
        ("Fit strategies", "fit_strategy_registry", "gelpy.core.peaks.strategies", fit_strategy_registry, "`fit run --method`"),
        ("Peak shapes", "peak_registry", "gelpy.core.peaks", peak_registry, "`fit run --shapes`"),
        ("Background models", "background_registry", "gelpy.core.background", background_registry, "`background remove --model`"),
        ("Lane projection strategies", "projection_strategies", "gelpy.core.lanes", projection_strategies, "`lanes detect --projection-strategy`"),
    ]

    lines = [
        GENERATED_MARKER,
        "",
        "# Registries (the extension points)",
        "",
        "gelpy has no if/elif dispatch on model names. Each pluggable family is a registry: a new",
        "entry is a subclass plus a decorator, and it becomes selectable from the CLI immediately.",
        "See [extending](../guide/extending.md) for what each one requires of a new entry.",
        "",
        "`gelpy models list --kind fit|shape|background` prints names, descriptions and parameter",
        "schemas at the terminal.",
        "",
    ]
    for title, variable, module, registry, flag in registries:
        lines.append(f"## {title}")
        lines.append("")
        lines.append(f"Selected with {flag}. Registry: `{module}.{variable}`.")
        lines.append("")
        descriptions = registry.descriptions()
        rows = [[f"`{name}`", _clean(descriptions.get(name))] for name in registry.names()]
        lines.append(_md_table(["name", "description"], rows))
        schemas = {k: v for k, v in registry.json_schemas().items() if v}
        if schemas:
            lines.append("")
            lines.append("Parameter schemas:")
            lines.append("")
            for name in sorted(schemas):
                props = schemas[name].get("properties", {})
                if not props:
                    continue
                lines.append(f"`{name}`:")
                lines.append("")
                rows = [
                    [
                        f"`{prop}`",
                        f"`{spec.get('type', 'any')}`",
                        f"`{spec['default']!r}`" if "default" in spec else "**required**",
                        _clean(spec.get("description")),
                    ]
                    for prop, spec in props.items()
                ]
                lines.append(_md_table(["parameter", "type", "default", "description"], rows))
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_errors() -> str:
    """The stable error-code catalogue an agent can branch on."""
    from gelpy.core import errors as errors_module

    lines = [
        GENERATED_MARKER,
        "",
        "# Error codes",
        "",
        "Every command failure is an `ErrorResponse` carrying a **stable** `code`, so a caller can",
        "branch on the kind of failure without string-matching a message. `available` lists the",
        "valid choices where there are any, which is usually enough to recover without reading",
        "source.",
        "",
        "```json",
        '{"error": "Unknown fit strategy model \'emg\'.", "code": "registry",',
        ' "available": ["bayesian", "grow_select", "sparse_seed"]}',
        "```",
        "",
        "## Domain errors",
        "",
    ]
    rows = []
    for name in sorted(dir(errors_module)):
        obj = getattr(errors_module, name)
        if isinstance(obj, type) and issubclass(obj, errors_module.GelpyError):
            rows.append([f"`{obj.code}`", f"`{name}`", _clean(obj.__doc__)])
    lines.append(_md_table(["code", "exception", "meaning"], rows))
    lines.append("")
    lines.append("## Codes from non-domain failures")
    lines.append("")
    lines.append(
        _md_table(
            ["code", "raised when"],
            [
                ["`not_found`", "a `FileNotFoundError` escaped (missing run folder or image)"],
                ["`validation_error`", "a pydantic `ValidationError`; `detail` carries the field errors as JSON"],
                ["`internal_error`", "any other exception, mapped rather than leaking a traceback"],
            ],
        )
    )
    return "\n".join(lines).rstrip("\n") + "\n"


def generate_run_folder() -> str:
    """The on-disk run-folder format, from RunPaths and the stage chain."""
    from gelpy.runfolder.layout import RunPaths
    from gelpy.runfolder.stages import StageName

    paths = RunPaths("<run_dir>")
    file_props = ["recipe", "fit_config", "manifest", "results_csv", "results_json", "report", "history"]
    dir_props = ["cache", "render", "render_fits", "log"]

    precious = {
        "recipe": "**precious** -- your editable intent: source image identity, lane layout, contrast, background choice. Hand-editable.",
        "fit_config": "**precious** -- per-lane `(profile, fit)` intent, sparse (only lanes actually fit). Deliberately NOT on the manifest, so it survives a cache wipe. Hand- and agent-editable.",
        "manifest": "**disposable** -- the cache ledger. Delete it and the next command rebuilds what it needs.",
        "results_csv": "generated -- one row per band, assembled from cached fits without recomputing.",
        "results_json": "generated -- the same content as the full structured result.",
        "report": "generated -- a human-readable markdown summary.",
        "history": "append-only log of every command run against this folder.",
    }

    lines = [
        GENERATED_MARKER,
        "",
        "# Run folder format",
        "",
        "A run folder is the unit of work and the unit of sharing. It is plain files: a collaborator",
        "can read the results without Python, and re-running any command reproduces them.",
        "",
        "```",
        "<run_dir>/",
    ]
    # Top-level files first, then directories with their contents nested underneath, so the
    # tree reads like `ls` rather than listing log/history.jsonl and log/ as separate peers.
    annotations = {
        "recipe": "precious, editable",
        "fit_config": "precious, editable",
        "manifest": "disposable cache ledger",
        "results_csv": "generated",
        "results_json": "generated",
        "report": "generated",
    }
    for prop in [p for p in file_props if p != "history"]:
        rel = str(getattr(paths, prop).relative_to(paths.root))
        lines.append(f"  {rel:<20} # {annotations[prop]}")
    lines += [
        "  cache/",
        "    image/<image_hash>.npy",
        "    background/<background_hash>.npz",
        "    profiles/lane_NNN__<profile_hash>.json",
        "    fits/lane_NNN__<fit_hash>.json",
        "  render/",
        "    *.png",
        "    fits/lane_NNN.png",
        "  log/",
        "    history.jsonl        # append-only command log",
    ]
    lines += ["```", "", "## What each entry is for", ""]
    rows = [
        [f"`{getattr(paths, prop).relative_to(paths.root)}`", precious[prop]]
        for prop in file_props
    ]
    lines.append(_md_table(["path", "role"], rows))

    lines += [
        "",
        "## Cache layout",
        "",
        "Cache filenames carry the content hash of the inputs that produced them, so a changed",
        "input writes a new file instead of invalidating an old one -- switching a setting back",
        "is a cache hit, not a recompute.",
        "",
        _md_table(
            ["artifact", "path"],
            [
                ["canonical image", f"`{paths.image_cache('<image_hash>').relative_to(paths.root)}`"],
                ["background-corrected image", f"`{paths.background_cache('<background_hash>').relative_to(paths.root)}`"],
                ["one lane's line profile", f"`{paths.profile_cache(0, '<profile_hash>').relative_to(paths.root)}`"],
                ["one lane's fit", f"`{paths.fit_cache(0, '<fit_hash>').relative_to(paths.root)}`"],
                ["one lane's fit plot", f"`{paths.fit_render(0).relative_to(paths.root)}`"],
            ],
        ),
        "",
        "## Stage chain",
        "",
        "```",
        "  " + " -> ".join(stage.value for stage in StageName),
        "```",
        "",
        "Every hash is computed from the recipe and small config objects -- never from the image",
        "pixels -- so deciding what to recompute costs a few sha256-over-small-JSON operations",
        "regardless of image size. See [concepts](../guide/concepts.md) for what feeds each hash",
        "and why some inputs are deliberately excluded.",
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


GENERATORS: dict[str, Any] = {
    "cli.md": generate_cli,
    "contracts.md": generate_contracts,
    "registries.md": generate_registries,
    "errors.md": generate_errors,
    "run-folder.md": generate_run_folder,
}


