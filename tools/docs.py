def build(write: bool = True) -> dict[Path, str]:
    """Generate every reference page and the index. Returns path -> content."""
    produced: dict[Path, str] = {}
    for name, generator in GENERATORS.items():
        produced[REFERENCE / name] = generator()
    produced[INDEX] = json.dumps(build_index(), indent=2) + "\n"

    if write:
        REFERENCE.mkdir(parents=True, exist_ok=True)
        for path, content in produced.items():
            path.write_text(content)
    return produced


def stamp(page: Path) -> tuple[bool, str]:
    """Recompute and write ``page``'s subject digest. Returns (changed, digest)."""
    text = page.read_text()
    front, body = split_front_matter(text)
    subjects = page_subjects(front)
    if not subjects:
        return False, ""
    digest = public_surface_digest(subjects, root=REPO)
    changed = front.get("subject_digest") != digest
    if changed:
        front["subject_digest"] = digest
        page.write_text(render_front_matter(front) + body)
    return changed, digest


def check() -> list[str]:
    """Every drift between the documentation and the code. Empty means clean."""
    problems: list[str] = []

    for path, expected in build(write=False).items():
        rel = path.relative_to(REPO)
        if not path.exists():
            problems.append(f"{rel}: missing (run `python tools/docs.py build`)")
        elif path.read_text() != expected:
            problems.append(f"{rel}: out of date (run `python tools/docs.py build`)")

    for page in guide_pages():
        front, _ = split_front_matter(page.read_text())
        rel = page.relative_to(REPO)
        if not front:
            problems.append(f"{rel}: no front matter (needs title/audience/summary/subject)")
            continue
        subjects = page_subjects(front)
        missing = [str(s.relative_to(REPO)) for s in subjects if not s.exists()]
        if missing:
            problems.append(f"{rel}: subject file(s) do not exist: {', '.join(missing)}")
            continue
        if not subjects:
            continue
        digest = public_surface_digest(subjects, root=REPO)
        recorded = front.get("subject_digest")
        if recorded != digest:
            problems.append(
                f"{rel}: the code it describes has changed "
                f"(recorded {recorded or 'nothing'}, now {digest}).\n"
                f"    Re-read the page against its subjects, then: "
                f"python tools/docs.py accept {rel}"
            )
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build", help="Regenerate docs/reference/ and docs/docs-index.json.")
    sub.add_parser("check", help="Report drift and exit 1 if any; write nothing.")
    accept = sub.add_parser("accept", help="Re-stamp a guide page after re-reading it.")
    accept.add_argument("page", nargs="*", type=Path, help="Pages to stamp (default: all).")
    for name in ("digest", "surface"):
        probe = sub.add_parser(name, help=f"Print the {name} of the given files.")
        probe.add_argument("paths", nargs="+", type=Path)

    args = parser.parse_args()

    if args.command == "build":
        for path in build(write=True):
            print(f"wrote {path.relative_to(REPO)}")
        return 0

    if args.command == "check":
        problems = check()
        for problem in problems:
            print(f"DRIFT {problem}")
        if problems:
            print(f"\n{len(problems)} problem(s).")
            return 1
        print("documentation is consistent with the code")
        return 0

    if args.command == "accept":
        pages = args.page or guide_pages()
        for page in pages:
            page = page if page.is_absolute() else REPO / page
            changed, digest = stamp(page)
            state = "re-stamped" if changed else "already current"
            print(f"{state}: {page.relative_to(REPO)} -> {digest or '(no subjects)'}")
        return 0

    paths = [p if p.is_absolute() else REPO / p for p in args.paths]
    if args.command == "digest":
        print(public_surface_digest(paths, root=REPO))
    else:
        print(surface_text(paths, root=REPO))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
