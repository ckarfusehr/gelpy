from typing import Any

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"
REFERENCE = DOCS / "reference"
GUIDE = DOCS / "guide"
WALKTHROUGH = DOCS / "walkthrough"
INDEX = DOCS / "docs-index.json"

sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "src"))

