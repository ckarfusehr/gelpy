"""What must never be committed.

The repository carries code, documentation and the public example data. These checks keep
machine-specific paths, analysis outputs and stray binary files out of it. They take the file
list from git's index (tracked plus staged files) and read the contents from the working tree,
so a staged file fails before it is committed.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path, PurePosixPath

import pytest

REPO = Path(__file__).resolve().parents[1]

#: The only directories allowed to hold binary files. Extend deliberately, never by default.
BINARY_DIRS = {
    "docs/walkthrough/img",  # figures generated by tools/build_walkthrough.py
    "examples/data",  # the example gels the tests and the walkthrough run against
}

#: Formats that are binary even when the first bytes happen to contain no NUL.
BINARY_SUFFIXES = {
    ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tif", ".tiff", ".pdf", ".npy", ".npz", ".pkl",
    ".pickle", ".h5", ".hdf5", ".zip", ".gz", ".xlsx", ".xls", ".docx", ".pptx",
}

#: An absolute path into a home directory (macOS, Linux, Windows). The look-behind skips a
#: Users or home segment inside a URL; a path at the end of a line or before a quote matches.
HOME_PATH = re.compile(
    r"(?<![\w.-])/(?:Users|home)/[^/\s'\"`<>)\]]+|[A-Za-z]:\\+Users\\+[^\\\s]+"
)

#: Files only a gelpy run folder contains; they record image paths, file names and timestamps.
RUN_FOLDER_FILES = {"recipe.json", "fit_config.json", "history.jsonl"}


def _tracked() -> list[str]:
    try:
        out = subprocess.run(
            ["git", "ls-files", "-z"], cwd=REPO, capture_output=True, check=True
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        pytest.skip("not a git checkout")
    return [name for name in out.decode().split("\0") if name and (REPO / name).is_file()]


def _is_binary(name: str) -> bool:
    if PurePosixPath(name).suffix.lower() in BINARY_SUFFIXES:
        return True
    with open(REPO / name, "rb") as f:
        return b"\0" in f.read(8000)  # git's own heuristic


def test_no_home_directory_paths_in_tracked_text():
    """An absolute home path records one machine's layout and works for nobody else. Use a
    path relative to the repository, or a placeholder such as /path/to/."""
    hits = []
    for name in _tracked():
        if _is_binary(name):
            continue
        text = (REPO / name).read_text(encoding="utf-8", errors="replace")
        for number, line in enumerate(text.splitlines(), 1):
            if HOME_PATH.search(line):
                hits.append(f"{name}:{number}: {line.strip()[:120]}")
    assert not hits, "absolute home-directory paths in tracked files:\n  " + "\n  ".join(hits)


def test_no_run_folder_files_outside_tests():
    """recipe.json, fit_config.json and log/history.jsonl are analysis output: they record the
    source image's path and file name and the time of every command. Analyses belong outside
    the repository; only test fixtures may carry such files."""
    found = sorted(
        name
        for name in _tracked()
        if PurePosixPath(name).name in RUN_FOLDER_FILES and PurePosixPath(name).parts[0] != "tests"
    )
    assert not found, "run-folder files outside tests/:\n  " + "\n  ".join(found)


def test_binary_files_only_in_allowlisted_directories():
    """Binary files are limited to the example gels and the generated walkthrough figures, so
    an image, PDF or cache file from a local analysis cannot slip in unnoticed."""
    stray = sorted(
        name
        for name in _tracked()
        if _is_binary(name) and str(PurePosixPath(name).parent) not in BINARY_DIRS
    )
    assert not stray, (
        "binary files outside "
        + ", ".join(sorted(BINARY_DIRS))
        + ":\n  "
        + "\n  ".join(stray)
        + "\n\nIf one belongs in the repository, add its directory to BINARY_DIRS with the reason."
    )
